# CELDA 2 – CARGA DE DATOS
# Lee el módulo 300 (Educación) de cada año 2004–2025, conserva solo las variables
# necesarias y las une en una sola tabla de personas (P). Crea variables derivadas:
# área (urbano/rural), sexo, lengua materna y años de estudio aproximados.
# 2026 queda fuera porque su ponderación no es comparable con la serie.
COLS = {'P301A':'nivel','P301B':'anio_est','P208A':'edad','P207':'sexo','P302':'sabe_leer',
        'P306':'matric','P300A':'lengua','ESTRATO':'estrato','FACTOR07':'peso'}
partes = []
for y in range(2004, 2026):                      # 2026 fuera: su ponderación no es comparable
    p = f'{BASE}/{y}/enaho01a-{y}-300.dta'       # nombre exacto (evita el 300a y el archivo 2009 de la carpeta 2010)
    d = pd.read_stata(p, convert_categoricals=False, convert_dates=False)
    d.columns = [c.upper() for c in d.columns]
    t = d[list(COLS)].apply(pd.to_numeric, errors='coerce').rename(columns=COLS)
    t['depto'] = d['UBIGEO'].astype(str).str.zfill(6).str[:2].astype(int)
    t['anio'] = y
    partes.append(t); print(y, 'ok', len(t)); del d
P = pd.concat(partes, ignore_index=True); del partes

P['area'] = np.where(P.estrato <= 5, 'Urbano', 'Rural')            # urbano = estratos 1-5 (2 000+ hab.)
P['sexo'] = P.sexo.map({1:'Hombre', 2:'Mujer'})
P['lengua_g'] = np.select([P.lengua == 4, P.lengua.isin([1,2,3]) | (P.lengua >= 10)], ['Castellano','Lengua originaria'], 'Otra')
P = P[P.nivel.notna() & (P.nivel != 99) & P.estrato.notna()].copy()
P['nivel'] = P.nivel.astype(int)

# años de estudio aproximados (supuesto: sup. no univ. completa=14, univ. completa=16, maestría=18, doctorado=21)
n, a = P.nivel.values, P.anio_est.fillna(-1).values
P['anios_est'] = np.select(
    [np.isin(n,[1,2]), n==3, n==4, n==5, n==6, n==7, n==8, n==9, n==10, np.isin(n,[11,13]), n==14],
    [0, np.where(a>=0, np.minimum(a,5), 3), 6, np.where(a>=0, 6+np.minimum(a,5), 8), 11,
     np.where(a>=0, 11+np.minimum(a,3), 12), 14, np.where(a>=0, 11+np.minimum(a,5), 13), 16, 18, 21], np.nan)
print(P.shape); P.head()

# CELDA 3 – INDICADORES
# Calcula por año y área (urbano/rural), ponderando con el factor de expansión:
# secundaria completa o más, estudios universitarios, sin nivel o primaria incompleta,
# años promedio de estudio (25+), analfabetismo (15+) y matrícula de 12–16 años.
# Guarda la tabla en CSV y muestra la comparación 2004 vs 2025.
NIV = {1:'Sin nivel/inicial', 2:'Sin nivel/inicial', 3:'Primaria', 4:'Primaria', 5:'Secundaria incompleta', 6:'Secundaria completa',
       7:'Superior no univ.', 8:'Superior no univ.', 9:'Superior univ.', 10:'Superior univ.', 11:'Maestría/doctorado', 13:'Maestría/doctorado', 14:'Maestría/doctorado'}
SEC, UNI, BAJ = [6,7,8,9,10,11,13,14], [9,10,11,13,14], [1,3]
wm = lambda x, w, m=None: np.nan if w.sum() == 0 else (x*w).sum()/w.sum()*100

def indicadores(df):
    filas = []
    for (y, ar), g in df.groupby(['anio','area']):
        a25 = g[g.edad >= 25]; a15 = g[g.edad >= 15]; e = g[(g.edad >= 12) & (g.edad <= 16)]
        w = a25.peso
        filas += [
         (y,ar,'Secundaria completa o más (25+)',   wm(a25.nivel.isin(SEC), w)),
         (y,ar,'Estudios universitarios (25+)',     wm(a25.nivel.isin(UNI), w)),
         (y,ar,'Sin nivel o primaria incompleta (25+)', wm(a25.nivel.isin(BAJ), w)),
         (y,ar,'Años promedio de estudio (25+)',    (a25.anios_est*w).sum()/w[a25.anios_est.notna()].sum()),
         (y,ar,'Analfabetismo (15+)',               wm(a15.sabe_leer.eq(2), a15.peso)),
         (y,ar,'Matriculados 12–16 años',           wm(e.matric.eq(1), e.peso)),
        ]
    return pd.DataFrame(filas, columns=['anio','area','indicador','valor'])

IND = indicadores(P)
IND_W = IND.pivot_table(index=['indicador','anio'], columns='area', values='valor').reset_index()
IND_W['brecha'] = IND_W.Urbano - IND_W.Rural
