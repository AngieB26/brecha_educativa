# CELDA 13 – MODELO: ÁRBOL DE DECISIÓN
# Pregunta: ¿se puede predecir si un adulto (25+) terminó la secundaria
# solo con su contexto (área, sexo, lengua materna, departamento, edad)?
# Datos: 2023–2025. 70 % entrenamiento / 30 % prueba. Ponderado con el factor de expansión.
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score, recall_score, precision_score, confusion_matrix, balanced_accuracy_score

M = P[(P.anio >= 2023) & (P.edad >= 25) & P.peso.notna()].copy()
M['y'] = M.nivel.isin(SEC).astype(int)                       # 1 = secundaria completa o más
M['departamento'] = M.depto.map(DEP)
X = pd.get_dummies(M[['area', 'sexo', 'lengua_g', 'departamento']], drop_first=False).astype(int)
X['edad'] = M.edad.values
y, w = M.y.values, M.peso.values

X_tr, X_te, y_tr, y_te, w_tr, w_te = train_test_split(X, y, w, test_size=0.3, random_state=42, stratify=y)
modelo = DecisionTreeClassifier(max_depth=6, min_samples_leaf=200, random_state=42)
modelo.fit(X_tr, y_tr, sample_weight=w_tr)
pred = modelo.predict(X_te)

# Línea base: predecir siempre la clase más frecuente (para saber si el modelo aporta algo)
base_clase = int(np.average(y_tr, weights=w_tr) >= 0.5)
base_acc = accuracy_score(y_te, np.full_like(y_te, base_clase), sample_weight=w_te)

met = {
    'Exactitud (accuracy)': accuracy_score(y_te, pred, sample_weight=w_te),
    'Exactitud balanceada': balanced_accuracy_score(y_te, pred, sample_weight=w_te),
    'Recall: detecta a quienes NO terminaron': recall_score(y_te, pred, pos_label=0, sample_weight=w_te),
    'Precisión al marcar "no terminó"': precision_score(y_te, pred, pos_label=0, sample_weight=w_te),
    'Línea base (siempre la clase mayoritaria)': base_acc,
}
display(pd.Series(met).mul(100).round(1).rename('%').to_frame())
print(f'Registros: {len(M):,} | entrenamiento: {len(X_tr):,} | prueba: {len(X_te):,}')

